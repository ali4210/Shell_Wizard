    show_header
    DETECTED_OS=$(detect_distro)
    echo -e "${YELLOW}Detected Host System:${NC} ${BOLD}${DETECTED_OS}${NC}\n"
    echo -e "Select target operating system environment to customize:\n"
    echo -e "  ${GREEN}[1]${NC} 🐧 Linux Workstation ${CYAN}(Debian, Ubuntu, Kali, RHEL, CentOS, Fedora, Arch)${NC}"
    echo -e "  ${GREEN}[2]${NC} 🍎 macOS Terminal ${CYAN}(Brew, Zsh, Starship, P10K Suite)${NC}"
    echo -e "  ${GREEN}[3]${NC} 🪟 Windows Host ${CYAN}(Launch Guidelines for PowerShell / autorun.bat)${NC}"
    echo -e "  ${GREEN}[4]${NC} Exit"
    echo -e "\n===================================================================="
    read -p "Select OS context [1-4]: " OS_CHOICE

    case $OS_CHOICE in
        1|2)
            if [[ -f "$LINUX_ENGINE" ]]; then
                chmod +x "$LINUX_ENGINE"
                echo -e "\n${GREEN}--> Launching Shell Wizard for POSIX / Unix Systems...${NC}\n"
                sleep 1
                exec "$LINUX_ENGINE"
            else
                echo -e "\n${RED}[!] Error: Could not locate '$LINUX_ENGINE'!${NC}"
                read -p "Press [ENTER] to return..."
            fi
            ;;
        3)
            clear
            show_header
            echo -e "${YELLOW}${BOLD}📌 HOW TO CUSTOMIZE WINDOWS POWERSHELL WORKSTATION${NC}"
            echo -e "${CYAN}====================================================================${NC}"
            echo -e " To deploy Oh My Posh, Terminal-Icons, and PSReadLine on Windows:\n"
            echo -e "  1. Open your Windows terminal or PowerShell window."
            echo -e "  2. Navigate to this cloned directory."
            echo -e "  3. **Double-click autorun.bat** (or run .\\autorun.bat)."
            echo -e "  4. PowerShell will elevate automatically and deploy Windows themes.\n"
            echo -e "${CYAN}====================================================================${NC}"
            read -p "Press [ENTER] to return to OS selection menu..."
            clear
            ;;
        4)
            echo -e "\n${GREEN}Make your terminal your masterpiece! Goodbye!${NC}"
            exit 0
            ;;
        *)
            echo -e "\n${RED}Invalid option!${NC}"
            sleep 1
            clear
            ;;
    esac
done