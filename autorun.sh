show_header() {
    echo -e "${CYAN}${BOLD}====================================================================${NC}"
    echo -e "${CYAN}${BOLD}   🧙‍♂️ SHELL-WIZARD ULTIMATE - OS TARGET SELECTION GATEWAY          ${NC}"
    echo -e "${CYAN}${BOLD}====================================================================${NC}"
    echo -e "${YELLOW}GitHub  :${NC} ${BOLD}https://github.com/ali4210${NC}\n"
}

detect_distro() {
    if [[ "$OSTYPE" == "darwin"* ]]; then
        echo "macOS"
    elif [ -f /etc/os-release ]; then
        . /etc/os-release
        echo "$NAME"
    else
        echo "Linux (Generic)"
    fi
}

show_banner

